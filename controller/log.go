func streamLogsCSV(c *gin.Context, query *gorm.DB, includeUsername bool, maxRows int) {
	if _, err := model.CountLogsForExport(query, maxRows); err != nil {
		common.ApiError(c, err)
		return
	}
	filename := "logs_" + time.Now().Format("20060102_150405") + ".csv"
	c.Header("Content-Type", "text/csv; charset=utf-8")
	c.Header("Content-Disposition", `attachment; filename="`+filename+`"`)
	c.Status(http.StatusOK)
	if err := model.StreamLogsCSV(c.Writer, query, includeUsername, maxRows); err != nil {
		// 响应头已发出，无法回退为 JSON，记录错误并断流
		common.SysError("export logs csv failed: " + err.Error())
	}
}

