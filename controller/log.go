func GetLogsStat(c *gin.Context) {
	logType, _ := strconv.Atoi(c.Query("type"))
	startTimestamp, _ := strconv.ParseInt(c.Query("start_timestamp"), 10, 64)
	endTimestamp, _ := strconv.ParseInt(c.Query("end_timestamp"), 10, 64)
	tokenName := c.Query("token_name")
	username := c.Query("username")
	modelName := c.Query("model_name")
	channel, _ := strconv.Atoi(c.Query("channel"))
	group := c.Query("group")
	quotaOnly, ok := parseStrictBoolQuery(c, "quota_only")
	if !ok {
		return
	}
	if quotaOnly {
		if logType != model.LogTypeConsume ||
			startTimestamp <= 0 ||
			endTimestamp <= startTimestamp ||
			endTimestamp-startTimestamp > 86400 ||
			channel <= 0 ||
			modelName != "" ||
			username != "" ||
			tokenName != "" ||
			group != "" {
			common.ApiErrorMsg(c, "quota_only=true requires type=2, a positive channel, a window up to 24h, and no model/username/token/group filters")
			return
		}
		quota, err := model.SumChannelQuota(c.Request.Context(), channel, startTimestamp, endTimestamp)
		if err != nil {
			common.ApiError(c, err)
			return
		}
		c.JSON(http.StatusOK, gin.H{
			"success": true,
			"message": "",
			"data": gin.H{
				"quota": quota,
			},
		})
		return
	}
	stat, err := model.SumUsedQuota(logType, startTimestamp, endTimestamp, modelName, username, tokenName, channel, group)
	if err != nil {
		common.ApiError(c, err)
		return
	}
	//tokenNum := model.SumUsedToken(logType, startTimestamp, endTimestamp, modelName, username, "")
	c.JSON(http.StatusOK, gin.H{
		"success": true,
		"message": "",
		"data": gin.H{
			"quota": stat.Quota,
			"rpm":   stat.Rpm,
			"tpm":   stat.Tpm,
		},
	})
	return
}

func parseStrictBoolQuery(c *gin.Context, key string) (bool, bool) {
	switch c.Query(key) {
	case "", "false":
		return false, true
	case "true":
		return true, true
	default:
		common.ApiErrorMsg(c, "invalid "+key+", must be true or false")
		return false, false
	}
}

