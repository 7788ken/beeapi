// recoverAutoDisabledChannels 仅扫描 status=AutoDisabled 且 permanent_disabled=0 的渠道，
// 对每个渠道做一次轻量探活；成功即调 service.EnableChannel（含 preChannelEnableHook，
// 把渠道恢复到 L1 而非 L0，给观察期）。
//
// Token 消耗：被禁渠道数 × 1 model × 1 次/probe_interval。生产通常 < 5% 渠道被禁，
// 假设 30min 间隔，相当于全量扫的 1-2%。
func recoverAutoDisabledChannels() error {
	channels, err := model.GetAutoDisabledChannelsForRecovery()
	if err != nil {
		common.SysError(fmt.Sprintf("[channel_health] recovery probe: failed to load AutoDisabled channels: %v", err))
		return err
	}
	if len(channels) == 0 {
		return nil
	}
	common.SysLog(fmt.Sprintf("[channel_health] recovery probe: probing %d AutoDisabled channels", len(channels)))

	for _, channel := range channels {
		// 跳过 AutoBan=false 的渠道
		if !channel.GetAutoBan() {
			continue
		}
		// 跳过 manually disabled（不应该出现在结果里，但兜底）
		if channel.Status != common.ChannelStatusManuallyDisabled {
			result := testChannelAuto(channel, shouldUseStreamForAutomaticChannelTest(channel))
			if result.newAPIError == nil {
				// 探活成功 → EnableChannel（preChannelEnableHook 会把它放回 L1）
				service.EnableChannel(channel.Id, common.GetContextKeyString(result.context, constant.ContextKeyChannelKey), channel.Name)
			}
		}
		time.Sleep(common.RequestInterval)
	}
	return nil
}

// probeDegradedChannels 对高降级等级但仍 enabled 的渠道做探测请求。
// 探测成功会通过 RecordChannelResult 累积 ok_streak，达到 UpgradeThreshold 后自动升级。
// 解决"降级死锁"：priority 太低 → 无真实流量 → ok_streak 永远为 0 → 无法恢复。
func probeDegradedChannels() {
	cfg := operation_setting.GetChannelHealthConfig()
	if !cfg.DegradeProbeEnabled {
		return
	}
	minLevel := cfg.DegradeProbeMinLevel
	if minLevel <= 0 {
		minLevel = 1
	}
	probeCount := cfg.DegradeProbeCount
	if probeCount <= 0 {
		probeCount = 5
	}

	channels, err := model.GetDegradedChannelsForProbe(minLevel)
	if err != nil {
		common.SysError(fmt.Sprintf("[channel_health] degrade probe: failed to load degraded channels: %v", err))
		return
	}
	if len(channels) == 0 {
		return
	}
	common.SysLog(fmt.Sprintf("[channel_health] degrade probe: probing %d channels (minLevel=L%d, count=%d)", len(channels), minLevel, probeCount))

	for _, channel := range channels {
		if !channel.GetAutoBan() {
			continue
		}
		for i := 0; i < probeCount; i++ {
			result := testChannelAuto(channel, shouldUseStreamForAutomaticChannelTest(channel))
			if result.newAPIError == nil {
				service.RecordChannelResult(channel.Id, "", nil, -1)
			} else {
				service.RecordChannelResult(channel.Id, "", result.newAPIError, -1)
				break
			}
			time.Sleep(common.RequestInterval)
		}
		time.Sleep(common.RequestInterval)
	}
}

var autoTestChannelsOnce sync.Once

// AutomaticallyTestChannels 定时探活后台 goroutine，三条互不干扰的循环：
//
//	1. 降级探测：channel_health_setting.enabled && degrade_probe_enabled，间隔 degrade_probe_minutes。
//	2. 恢复探活：channel_health_setting.enabled && recovery_strategy=probe，间隔 recovery_probe_minutes，
//	   只扫 AutoDisabled+permanent_disabled=0 的渠道。
//	3. 全量定时测试：monitor_setting.auto_test_channel_enabled，间隔 auto_test_channel_minutes。
//
// 被动健康（降级/熔断）与主动全量测试是两个正交能力：前者靠真实流量判渠道好坏，后者给无流量的
// 渠道提供可用性证据。曾经把 1、2 与 3 写成互斥（被动模式开就跳过全量扫），结果开了被动模式后
// 全量测试被静默劫持，管理员在后台配的 15 分钟定时测试完全不执行、可用性列也永远没有数据。
//
// 触发频率：各循环用各自的间隔睡眠；开关关闭时按 1 分钟轮询配置变更。
func waitChannelTask(ctx context.Context, delay time.Duration) bool {
	timer := time.NewTimer(delay)
	defer timer.Stop()
	select {
	case <-ctx.Done():
		return false
	case <-timer.C:
		return true
	}
}

func AutomaticallyTestChannels() error {
	// 只在Master节点定时测试渠道
	if !common.IsMasterNode {
		return nil
	}
	var startErr error
	autoTestChannelsOnce.Do(func() {
		startErr = backgroundtask.Start("automatic-channel-tests", func(ctx context.Context) {
			var probeWG sync.WaitGroup
			probeWG.Add(2)
			go func() {
				defer probeWG.Done()
				// 降级渠道探测恢复（间隔独立于恢复探活）
				for {
					cfg := operation_setting.GetChannelHealthConfig()
					delay := time.Minute
					if cfg.Enabled && cfg.DegradeProbeEnabled {
						probeMin := cfg.DegradeProbeMinutes
						if probeMin <= 0 {
							probeMin = 10
						}
						delay = time.Duration(probeMin) * time.Minute
					}
					if !waitChannelTask(ctx, delay) {
						return
					}
					if cfg.Enabled && cfg.DegradeProbeEnabled {
						probeDegradedChannels()
					}
				}
			}()
			go func() {
				defer probeWG.Done()
				// AutoDisabled 渠道恢复探活（仅被动模式 probe 策略）
				for {
					cfg := operation_setting.GetChannelHealthConfig()
					strategy := cfg.RecoveryStrategy
					if strategy == "" {
						strategy = "probe"
					}
					enabled := cfg.Enabled && strategy == "probe"
					delay := time.Minute
					probeMinutes := cfg.RecoveryProbeMinutes
					if probeMinutes <= 0 {
						probeMinutes = 30
					}
					if enabled {
						delay = time.Duration(probeMinutes) * time.Minute
					}
					if !waitChannelTask(ctx, delay) {
						return
					}
					if enabled {
						common.SysLog(fmt.Sprintf("[channel_health] recovery probe tick (interval=%dm, target=AutoDisabled only)", probeMinutes))
						_ = recoverAutoDisabledChannels()
					}
				}
			}()
			defer probeWG.Wait()

			for {
				monitor := operation_setting.GetMonitorSetting()

				// 全量定时测试：只受 monitor_setting 控制，与被动健康模式无关
				if !monitor.AutoTestChannelEnabled {
					if !waitChannelTask(ctx, time.Minute) {
						return
					}
					continue
				}
				frequency := monitor.AutoTestChannelMinutes
				if frequency <= 0 {
					frequency = 10
				}
				if !waitChannelTask(ctx, time.Duration(int(math.Round(frequency)))*time.Minute) {
					return
				}
				common.SysLog(fmt.Sprintf("automatically test channels with interval %f minutes", frequency))
				common.SysLog("automatically testing all channels")
				_ = testAllChannels(false)
				common.SysLog("automatically channel test finished")
			}
		})
	})
	return startErr
}
